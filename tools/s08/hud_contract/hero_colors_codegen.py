"""HUD "Стол" (docs/game-design/hud-redesign/03-CONCEPT.md §3.1, R3 P-5): the hero identity colour of the hero card -
the backend's Hero.color by hero key (scraped-data/api/heroes.json, the admin's data) - as a generated C++ header.

  python tools/s08/hud_contract/hero_colors_codegen.py [--check]

Writes unreal/Unmatched/Source/Unmatched/S08/UI/UmHeroColors.generated.h; --check fails when the header is stale.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "scraped-data/api/heroes.json"
OUT = ROOT / "unreal/Unmatched/Source/Unmatched/S08/UI/UmHeroColors.generated.h"


def colors() -> dict:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    arr = [n for n in d["nodes"] if n and "data" in n and len(n["data"]) > 1000][0]["data"]
    out = {}
    for v in arr:
        if isinstance(v, dict) and isinstance(v.get("key"), int) and isinstance(v.get("color"), int):
            key, color = arr[v["key"]], arr[v["color"]]
            if isinstance(key, str) and isinstance(color, str) and color.startswith("#") and len(color) == 7:
                out[key] = color.lower()
    return dict(sorted(out.items()))


def render(table: dict) -> str:
    rows = "\n".join(f'      {{TEXT("{k}"), FColor(0x{c[1:3]}, 0x{c[3:5]}, 0x{c[5:7]})}},' for k, c in table.items())
    return f"""// GENERATED by tools/s08/hud_contract/hero_colors_codegen.py from scraped-data/api/heroes.json - do not edit.
// HUD "Стол": the hero identity colour (backend Hero.color) of the hero card's band, by hero key ({len(table)} heroes).
#pragma once

#include "CoreMinimal.h"

namespace UmHeroColors {{
/** The backend colour of the hero key ("medusa", "king-arthur"); false when the hero has none. */
inline bool Find(const FString& HeroKey, FColor& OutColor) {{
  static const TMap<FString, FColor> Table = {{
{rows}
  }};
  if (const FColor* C = Table.Find(HeroKey.ToLower())) {{
    OutColor = *C;
    return true;
  }}
  return false;
}}
}}  // namespace UmHeroColors
"""


def main() -> int:
    text = render(colors())
    if "--check" in sys.argv[1:]:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("hero colors header", "up to date" if ok else "STALE")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
