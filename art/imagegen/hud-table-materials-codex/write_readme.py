for record in validation['plates']:
    family, plate = record['family'], record['plate']
    image = Image.open(root / family / f'{plate}.png')
    if plate == 'hp-dial':
        row = np.array(image)[128, :, :3].mean(axis=1)
        left, right = 128, 128
        while left > 0 and row[left - 1] > 150:
            left -= 1
        while right < 255 and row[right + 1] > 150:
            right += 1
        diameter = right - left + 1
        assert 116 <= diameter <= 120, diameter
        record['cream_window_diameter_px'] = diameter
    record['visual_no_text_numbers_logos'] = True
    raw_size = '×'.join(map(str, record['raw_size']))
    size = '×'.join(map(str, record['normalized_size']))
    lines.append(f'| `{family}/{plate}.png` | {raw_size} | {size} | отсутствуют |')

